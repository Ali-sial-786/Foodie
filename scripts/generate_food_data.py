#!/usr/bin/env python3
"""Generates Nouri's food reference data from USDA SR28 (public domain).

Inputs (committed, see data/usda-sr28/README.md):
  data/usda-sr28/ABBREV.txt   SR28 abbreviated nutrient file (per 100 g edible portion)
  data/usda-sr28/FOOD_DES.txt SR28 food descriptions

Outputs:
  shared/src/commonMain/kotlin/app/nouri/core/fooddb/generated/UsdaCoreFoods.kt
      Records referenced from the ingredient ontology / dish catalog, compiled into
      the shared module so the nutrition engine works offline on every platform.
  app/src/main/assets/fooddb/usda_sr28.tsv
      The full table in a compact TSV used for food search in the Android app.

Usage: python3 scripts/generate_food_data.py [--check]
  --check  exit non-zero if the generated files are out of date (used in CI).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "data", "usda-sr28")
SHARED_SRC = os.path.join(ROOT, "shared", "src", "commonMain", "kotlin", "app", "nouri", "core")
KOTLIN_OUT = os.path.join(SHARED_SRC, "fooddb", "generated", "UsdaCoreFoods.kt")
TSV_OUT = os.path.join(ROOT, "app", "src", "main", "assets", "fooddb", "usda_sr28.tsv")

# SR28 ABBREV.txt field positions (0-based); see SR28 documentation, Table 2.
F_NDB, F_DESC, F_KCAL, F_PROT, F_FAT, F_CARB, F_FIBER, F_SUGAR = 0, 1, 3, 4, 5, 7, 8, 9
F_SODIUM, F_SATFAT, F_W1, F_D1, F_W2, F_D2, F_REFUSE = 15, 44, 48, 49, 50, 51, 52

# Groups excluded from the search asset (not useful for diary logging).
EXCLUDED_GROUPS = {"0300"}  # baby foods

REF_PATTERNS = [
    re.compile(r'\bndb\s*=\s*"(\d{5})"'),
    re.compile(r'cookedNdb\s*=\s*"(\d{5})"'),
    re.compile(r'"usda:(\d{5})"'),
]


def read_caret_file(path):
    with open(path, encoding="latin-1") as fh:
        for line in fh:
            line = line.rstrip("\r\n")
            if line:
                yield [field.strip("~") for field in line.split("^")]


def num(value):
    value = value.strip()
    return value if value != "" else ""


def load():
    descriptions = {}
    for f in read_caret_file(os.path.join(DATA, "FOOD_DES.txt")):
        descriptions[f[0]] = {"group": f[1], "name": f[2]}
    foods = {}
    for f in read_caret_file(os.path.join(DATA, "ABBREV.txt")):
        ndb = f[F_NDB]
        d = descriptions[ndb]
        foods[ndb] = {
            "ndb": ndb,
            "group": d["group"],
            "name": d["name"],
            "kcal": num(f[F_KCAL]),
            "protein": num(f[F_PROT]),
            "fat": num(f[F_FAT]),
            "carbs": num(f[F_CARB]),
            "fiber": num(f[F_FIBER]),
            "sugar": num(f[F_SUGAR]),
            "sodium": num(f[F_SODIUM]),
            "satfat": num(f[F_SATFAT]),
            "w1": num(f[F_W1]),
            "d1": f[F_D1].strip(),
            "w2": num(f[F_W2]),
            "d2": f[F_D2].strip(),
            "refuse": num(f[F_REFUSE]),
        }
    return foods


def referenced_ndbs():
    refs = set()
    for dirpath, _, files in os.walk(SHARED_SRC):
        if "generated" in dirpath:
            continue
        for name in files:
            if name.endswith(".kt"):
                text = open(os.path.join(dirpath, name), encoding="utf-8").read()
                for pattern in REF_PATTERNS:
                    refs.update(pattern.findall(text))
    return refs


def kstr(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def kdouble(value, nullable=True):
    if value == "":
        return "null" if nullable else "0.0"
    return repr(float(value))


def kotlin_source(foods, refs):
    missing = sorted(r for r in refs if r not in foods)
    if missing:
        raise SystemExit(f"Referenced NDB numbers not in SR28: {missing}")
    rows = [foods[r] for r in sorted(refs)]
    chunks = [rows[i:i + 80] for i in range(0, len(rows), 80)]
    out = [
        "// GENERATED by scripts/generate_food_data.py from USDA SR28 — do not edit by hand.",
        "// Source: U.S. Department of Agriculture, Agricultural Research Service. USDA National",
        "// Nutrient Database for Standard Reference, Release 28 (2015, revised 2016). Public domain.",
        "package app.nouri.core.fooddb.generated",
        "",
        "import app.nouri.core.fooddb.FoodReference",
        "import app.nouri.core.fooddb.UsdaSr28",
        "",
        "internal object UsdaCoreFoods {",
        f"    const val COUNT = {len(rows)}",
        "",
        "    val all: List<FoodReference> by lazy { " + " + ".join(f"part{i}()" for i in range(len(chunks))) + " }",
    ]
    for i, chunk in enumerate(chunks):
        out.append("")
        out.append(f"    private fun part{i}(): List<FoodReference> = listOf(")
        for r in chunk:
            out.append(
                "        UsdaSr28.food("
                f"{kstr(r['ndb'])}, {kstr(r['name'])}, {kstr(r['group'])}, "
                f"{kdouble(r['kcal'], False)}, {kdouble(r['protein'], False)}, {kdouble(r['fat'], False)}, "
                f"{kdouble(r['carbs'], False)}, {kdouble(r['fiber'])}, {kdouble(r['sugar'])}, "
                f"{kdouble(r['sodium'])}, {kdouble(r['satfat'])}, "
                f"{kdouble(r['w1'])}, {kstr(r['d1']) if r['d1'] else 'null'}, "
                f"{kdouble(r['w2'])}, {kstr(r['d2']) if r['d2'] else 'null'}, {kdouble(r['refuse'])}),"
            )
        out.append("    )")
    out.append("}")
    return "\n".join(out) + "\n"


def tsv_source(foods):
    header = "#ndb\tgroup\tname\tkcal\tprotein\tfat\tcarbs\tfiber\tsugar\tsodium_mg\tsatfat\tw1\tmeasure1\tw2\tmeasure2\trefuse_pct"
    lines = [header, "# Source: USDA National Nutrient Database for Standard Reference, Release 28 (public domain)"]
    for ndb in sorted(foods):
        r = foods[ndb]
        if r["group"] in EXCLUDED_GROUPS:
            continue
        fields = [r[k] for k in ("ndb", "group", "name", "kcal", "protein", "fat", "carbs", "fiber", "sugar",
                                 "sodium", "satfat", "w1", "d1", "w2", "d2", "refuse")]
        lines.append("\t".join(x.replace("\t", " ") for x in fields))
    return "\n".join(lines) + "\n"


def write_or_check(path, content, check):
    current = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if current == content:
        return True
    if check:
        print(f"OUT OF DATE: {os.path.relpath(path, ROOT)}")
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    print(f"wrote {os.path.relpath(path, ROOT)}")
    return True


def main():
    check = "--check" in sys.argv
    foods = load()
    refs = referenced_ndbs()
    ok = write_or_check(KOTLIN_OUT, kotlin_source(foods, refs), check)
    ok = write_or_check(TSV_OUT, tsv_source(foods), check) and ok
    print(f"{len(refs)} referenced records, {len(foods)} foods in SR28")
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
