package app.nouri.core.recipes

import app.nouri.core.ontology.Allergen
import app.nouri.core.ontology.DietGoal
import app.nouri.core.units.Quantity
import kotlinx.serialization.Serializable

@Serializable
enum class Difficulty(val label: String) { EASY("Easy"), MEDIUM("Medium"), INVOLVED("Involved") }

/**
 * Where a recipe came from. Nouri never invents a published source: generated
 * recipes are labelled AI-generated, and editorial reference recipes are labelled
 * as Nouri's own write-ups of widely known traditional dishes.
 */
@Serializable
enum class RecipeOrigin(val label: String) {
    /** Nouri's editorial write-up of a traditional dish (no external source claimed). */
    EDITORIAL_TRADITIONAL("Traditional (Nouri reference recipe)"),

    /** A deliberately modified version of a traditional recipe; never presented as the original. */
    EDITORIAL_VARIATION("Variation"),

    /** Generated by an AI provider for this user. */
    AI_GENERATED("AI-generated"),

    /** Created or edited by the user. */
    USER("Your recipe"),

    /** Imported from an external source whose licence permits it; see attribution. */
    EXTERNAL_LICENSED("External recipe"),

    /**
     * Saved by the user from pasted text or screenshots for their own use. Kept as written;
     * attribution names the source only when the original stated it.
     */
    IMPORTED("Saved from text or a screenshot"),
}

@Serializable
data class RecipeIngredient(
    /** Free text as written ("2 medium onions, thinly sliced"). */
    val displayName: String,
    /** Canonical ingredient id once resolved; null if unresolved. */
    val ingredientId: String? = null,
    val quantity: Quantity,
    val preparation: String? = null,
    val optional: Boolean = false,
    /** Section heading such as "Marinade" or "Tempering (tadka)". */
    val group: String? = null,
    /**
     * Fraction of this ingredient that ends up eaten. Frying oil (most of it stays in
     * the pan), whole spices removed before serving, and discarded marinades are below 1.
     */
    val consumedFraction: Double = 1.0,
    /** Explicit nutrition record (e.g. a scanned branded product) overriding the ontology default. */
    val foodRefId: String? = null,
    /** Use the cooked-state reference (e.g. "300 g cooked rice"). */
    val measuredCooked: Boolean = false,
    /** User-measured grams, overriding household-unit conversion. */
    val gramsOverride: Double? = null,
) {
    init {
        require(consumedFraction in 0.0..1.0) { "consumedFraction must be within 0..1" }
    }
}

@Serializable
data class RecipeStep(
    val text: String,
    val timerSeconds: Int? = null,
    /** Target temperature in °C for ovens/oil/internal doneness where relevant. */
    val temperatureC: Int? = null,
)

@Serializable
data class Recipe(
    val id: String,
    val name: String,
    val cuisineId: String,
    val region: String? = null,
    val description: String = "",
    val servings: Int,
    val ingredients: List<RecipeIngredient>,
    val steps: List<RecipeStep>,
    val prepMinutes: Int,
    val cookMinutes: Int,
    val difficulty: Difficulty = Difficulty.MEDIUM,
    val equipment: List<String> = emptyList(),
    val tags: Set<String> = emptySet(),
    val origin: RecipeOrigin,
    /** For variations: id of the traditional recipe this was derived from. */
    val variantOf: String? = null,
    val variantSummary: String? = null,
    /** Required for EXTERNAL_LICENSED recipes. */
    val attribution: String? = null,
    val storage: String? = null,
    val reheating: String? = null,
    val foodSafety: List<String> = emptyList(),
    /** Measured total cooked weight of the batch, if the cook weighed it. */
    val cookedYieldGrams: Double? = null,
    val notes: List<String> = emptyList(),
    /** Declared by the author/AI; verified against ingredients by [RecipeAnalyzer]. */
    val declaredDiets: Set<DietGoal> = emptySet(),
    val declaredAllergens: Set<Allergen> = emptySet(),
    val createdAtEpochMs: Long = 0,
) {
    init {
        require(servings >= 1) { "A recipe needs at least one serving" }
        require(origin != RecipeOrigin.EXTERNAL_LICENSED || !attribution.isNullOrBlank()) {
            "External recipes must carry attribution"
        }
    }

    val totalMinutes: Int get() = prepMinutes + cookMinutes
}
